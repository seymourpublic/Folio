import { PDFDocument } from "pdf-lib";

export type AuditEventType =
  | "opened"
  | "annotated"
  | "form-filled"
  | "signed"
  | "encrypted"
  | "redacted"
  | "compressed"
  | "exported"
  | "metadata-scrubbed"
  | "custom";

export type AuditEvent = {
  id: string;
  timestamp: number;
  type: AuditEventType;
  detail: string;
  actor?: string;
};

export const AUDIT_ATTACHMENT_NAME = "audit-trail.json";

/**
 * Embeds a session's audit trail as a JSON attachment so it travels with the exported file and is readable later.
 */
export async function embedAuditTrailAttachment(doc: PDFDocument, events: AuditEvent[], fileName: string): Promise<void> {
  if (events.length === 0) return;
  const payload = JSON.stringify({ fileName, exportedAt: new Date().toISOString(), events }, null, 2);
  await doc.attach(new TextEncoder().encode(payload), AUDIT_ATTACHMENT_NAME, {
    mimeType: "application/json",
    description: "Document activity & signature audit trail (generated by this app)",
    creationDate: new Date(),
    modificationDate: new Date(),
  });
}
